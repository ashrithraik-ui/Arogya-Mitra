"""
ArogyaMitra AI — Application Configuration
Reads settings from environment variables or .env file.
"""

from pydantic_settings import BaseSettings
from typing import Optional
import os


class Settings(BaseSettings):
    # ── Application ──────────────────────────────────────────────────────────
    APP_NAME: str = "ArogyaMitra AI"
    APP_VERSION: str = "1.0.0"
    APP_DESCRIPTION: str = (
        "Agentic AI Healthcare Assistant — AI assists, Doctor decides."
    )
    DEBUG: bool = False

    # ── Database ─────────────────────────────────────────────────────────────
    # Uses its own env var to avoid conflict with any workspace PostgreSQL DATABASE_URL
    AROGYA_DATABASE_URL: str = "sqlite+aiosqlite:///./arogya_mitra.db"

    # ── Authentication ────────────────────────────────────────────────────────
    SECRET_KEY: str = "change-this-key-in-production-use-openssl-rand-hex-32"
    ALGORITHM: str = "HS256"
    ACCESS_TOKEN_EXPIRE_MINUTES: int = 60 * 24  # 24 hours

    # ── Gemini AI (Future / Optional) ─────────────────────────────────────────
    GEMINI_API_KEY: Optional[str] = None
    GEMINI_MODEL: str = "gemini-1.5-flash"
    GEMINI_VISION_MODEL: str = "gemini-1.5-flash"
    GEMINI_MAX_TOKENS: int = 2048
    GEMINI_TEMPERATURE: float = 0.7

    # ── File Storage ──────────────────────────────────────────────────────────
    UPLOAD_DIR: str = "./storage/uploads"
    MAX_FILE_SIZE_MB: int = 20  # Maximum upload size in MB
    ALLOWED_IMAGE_TYPES: list[str] = ["image/jpeg", "image/png", "image/webp", "image/gif"]
    ALLOWED_DOC_TYPES: list[str] = ["application/pdf", "image/jpeg", "image/png"]

    # ── CORS ──────────────────────────────────────────────────────────────────
    CORS_ORIGINS: list[str] = ["*"]

    # ── AI Safety Disclaimer ─────────────────────────────────────────────────
    AI_DISCLAIMER: str = (
        "This summary is generated by AI to assist the doctor. "
        "The AI does NOT diagnose, prescribe, or determine risk levels. "
        "All clinical decisions rest solely with the treating physician."
    )

    model_config = {
        "env_file": [
            os.path.join(os.path.dirname(__file__), ".env"),
            ".env"
        ],
        "case_sensitive": True,
        "extra": "ignore"
    }


# Singleton instance used across the application
settings = Settings()
